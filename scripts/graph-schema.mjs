// The JSON schema is generated from the canonical types; --check detects drift in CI.
import { createGenerator } from 'ts-json-schema-generator';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const schema = createGenerator({ path: `${root}packages/graph/src/document.ts`, tsconfig: `${root}packages/graph/tsconfig.json`, type: 'GraphDocument', additionalProperties: false }).createSchema('GraphDocument');
schema.$id = 'https://github.com/zalos/farsight/schemas/graph-v1.schema.json';
const text = JSON.stringify(schema, null, 2) + '\n';
const moduleText = '// Generated by scripts/graph-schema.mjs from the canonical graph contract.\nexport default ' + JSON.stringify(schema) + ';\n';
const moduleFile = `${root}packages/graph/src/schema.ts`;
const file = `${root}packages/graph/schemas/graph-v1.schema.json`;
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== text || readFileSync(moduleFile, 'utf8') !== moduleText) throw new Error('Graph schema differs from canonical types; run node scripts/graph-schema.mjs');
} else { mkdirSync(`${root}packages/graph/schemas`, { recursive: true }); writeFileSync(file, text); writeFileSync(moduleFile, moduleText); }
