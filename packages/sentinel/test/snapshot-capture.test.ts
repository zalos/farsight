const sha = (b: Buffer | string) => `sha256:${createHash('sha256').update(b).digest('hex')}`;
const coded = (code: string) => (e: unknown) => e instanceof SnapshotError && e.code === code;
const entryOf = (snap: any, path: string, sourceId = 'app') => snap.entries.find((e: any) => e.sourceId === sourceId && e.relativePath === path);

// Bytes a filter, a line-ending conversion or a text decode would change.
const RAW = Buffer.concat([Buffer.from('const s = "café";\r\nconst t = 1;\r\n'), Buffer.from([0xff, 0xfe, 0x00, 0x80, 0x0d])]);

