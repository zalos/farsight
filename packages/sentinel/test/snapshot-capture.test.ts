test('packed history, missing and corrupt objects, unsafe and colliding names are recorded, never dropped', needsStore, async t => {
  const dir = scratch(t);
  const root = join(dir, 'repo');
  commitRepo(root, { 'keep.ts': 'keep\n', 'gone.ts': 'gone\n', 'bad.ts': 'bad\n', 'lib/inner.ts': 'inner\n', 'lib2/x.ts': 'x\n' });
  // A tree with names a checkout would refuse, and two paths that differ only by case, made with plumbing.
  const blob = git(root, ['hash-object', '-w', '--stdin'], 'payload\n').trim();
  const evil = git(root, ['hash-object', '-w', '-t', 'tree', '--literally', '--stdin'], Buffer.concat([
    Buffer.from(`100644 ..\0`), Buffer.from(blob, 'hex'),
    Buffer.from(`100644 .git\0`), Buffer.from(blob, 'hex'),
    Buffer.from(`100644 a\\b\0`), Buffer.from(blob, 'hex'),
    Buffer.from('100644 '), Buffer.from([0x62, 0xff, 0x00]), Buffer.from(blob, 'hex'),
  ])).trim();
  git(root, ['update-index', '--add', '--cacheinfo', `100644,${blob},README`]);
  git(root, ['update-index', '--add', '--cacheinfo', `100644,${blob},readme`]);
  git(root, ['update-index', '--add', '--cacheinfo', `100644,${blob},Docs/x.md`]);
  git(root, ['update-index', '--add', '--cacheinfo', `100644,${blob},docs/y.md`]);
  // Checkout-level commands refuse such names, so the root tree and commit are assembled with plumbing.
  const indexTree = git(root, ['write-tree']).trim();
  const rootTree = git(root, ['mktree'], git(root, ['ls-tree', indexTree]) + `040000 tree ${evil}\tevil\n`).trim();
  const commit = git(root, ['commit-tree', rootTree, '-p', 'HEAD', '-m', 'evil']).trim();
  git(root, ['update-ref', 'refs/heads/main', commit]);
  git(root, ['gc', '--quiet', '--prune=now']);
  // After packing: drop one blob and one tree from the pack by rewriting it without them is heavy, so use loose
  // copies instead: unpack everything, then remove and corrupt specific objects.
  const packs = readdirSync(join(root, '.git/objects/pack')).filter(n => n.endsWith('.pack'));
  const moved = join(dir, 'packs');
  mkdirSync(moved);
  for (const p of readdirSync(join(root, '.git/objects/pack'))) renameSync(join(root, '.git/objects/pack', p), join(moved, p));
  for (const p of packs) git(root, ['unpack-objects', '-q'], readFileSync(join(moved, p)));
  const oid = (path: string) => git(root, ['rev-parse', `HEAD:${path}`]).trim();
  const loose = (o: string) => join(root, '.git/objects', o.slice(0, 2), o.slice(2));
  const lib = oid('lib');
  // The independent listing, taken while every object is still present.
  const listed = git(root, ['ls-tree', '-r', '-z', '--name-only', 'HEAD']).split('\0').filter(Boolean);
  const bad = oid('bad.ts');
  rmSync(loose(oid('gone.ts')));
  rmSync(loose(lib));
  chmodSync(loose(bad), 0o600);
  writeFileSync(loose(bad), readFileSync(loose(oid('keep.ts'))));

  const fx = await openCaptureStore(t, dir);
  const { snapshot: snap } = await captureSnapshot(fx.store, { mode: 'committed-tree',
    sources: [{ sourceId: 'app', repositoryId: 'example/app', root }] });
  assert.equal(entryOf(snap, 'keep.ts').disposition, 'included');
  assert.deepEqual([entryOf(snap, 'gone.ts').disposition, entryOf(snap, 'gone.ts').reasonCode], ['unreadable', 'sentinel.capture.gitObjectMissing']);
  assert.deepEqual([entryOf(snap, 'bad.ts').disposition, entryOf(snap, 'bad.ts').reasonCode], ['unreadable', 'sentinel.capture.gitObjectCorrupt']);
  assert.deepEqual(entryOf(snap, 'lib'), { sourceId: 'app', relativePath: 'lib', kind: 'directory-boundary', disposition: 'unreadable',
    reasonCode: 'sentinel.capture.gitObjectMissing', knownDescendants: null }, 'a missing tree is unknown scope, not zero files');
  const refused = snap.entries.filter((e: any) => e.relativePath.startsWith('evil/')).map((e: any) => [e.disposition, e.reasonCode]);
  assert.deepEqual(refused.sort(), [
    ['refused', 'sentinel.capture.pathEncoding'], ['refused', 'sentinel.capture.unsafePath'],
    ['refused', 'sentinel.capture.unsafePath'], ['refused', 'sentinel.capture.unsafePath'],
  ]);
  for (const p of ['README', 'readme', 'Docs/x.md', 'docs/y.md']) {
    assert.deepEqual([entryOf(snap, p).disposition, entryOf(snap, p).reasonCode], ['refused', 'sentinel.capture.caseCollision'], p);
  }
  assert.equal(validateEnvelope('snapshot', snap).ok, true);
  // E1: every path git lists (and the evil tree's raw entries) is accounted for.
  const rec = reconcileInventory(snap, 'app', listed.filter(p => !p.startsWith('evil/')));
  assert.deepEqual(rec.unaccounted, []);
  assert.equal(rec.insideBoundary, 1, 'lib/inner.ts sits inside the missing tree');
});

test('LFS pointers resolve only from a permitted local store; submodules only from a permitted local clone', needsStore, async t => {
  const dir = scratch(t);
  const content = Buffer.from('real large payload\n');
  const oidHex = createHash('sha256').update(content).digest('hex');
  const pointer = `version https://git-lfs.github.com/spec/v1\noid sha256:${oidHex}\nsize ${content.length}\n`;
  const sub = join(dir, 'sub');
  const subHead = commitRepo(sub, { 'lib.ts': 'export const lib = 1;\n' });
  const root = join(dir, 'repo');
  commitRepo(root, { 'asset.bin': pointer, 'wrong.bin': pointer.replace(/size \d+/, 'size 3') });
  git(root, ['update-index', '--add', '--cacheinfo', `160000,${subHead},vendor/sub`]);
  git(root, ['update-index', '--add', '--cacheinfo', `160000,${'1'.repeat(40)},vendor/gone`]);
  git(root, ['update-index', '--add', '--cacheinfo', `160000,${subHead},vendor/unpermitted`]);
  git(root, ['commit', '--quiet', '-m', 'links']);
  const lfs = join(dir, 'lfs-objects');
  mkdirSync(join(lfs, oidHex.slice(0, 2), oidHex.slice(2, 4)), { recursive: true });
  writeFileSync(join(lfs, oidHex.slice(0, 2), oidHex.slice(2, 4), oidHex), content);

  const fx = await openCaptureStore(t, dir);
  const without = (await captureSnapshot(fx.store, { mode: 'committed-tree',
    sources: [{ sourceId: 'app', repositoryId: 'example/app', root }] })).snapshot;
  assert.deepEqual([entryOf(without, 'asset.bin').disposition, entryOf(without, 'asset.bin').reasonCode, entryOf(without, 'asset.bin').bytes],
    ['unreadable', 'sentinel.capture.lfsObjectMissing', content.length]);
  assert.equal(entryOf(without, 'vendor/sub').reasonCode, 'sentinel.capture.submoduleNotCaptured');
  assert.equal(entryOf(without, 'vendor/sub').knownDescendants, null);

  const withInputs = (await captureSnapshot(fx.store, { mode: 'committed-tree', sources: [{
    sourceId: 'app', repositoryId: 'example/app', root, lfsObjects: lfs,
    submodules: [
      { path: 'vendor/sub', sourceId: 'app-sub', repositoryId: 'example/sub', root: sub },
      { path: 'vendor/gone', sourceId: 'app-gone', repositoryId: 'example/gone', root: sub },
    ],
  }] })).snapshot;
  assert.equal(entryOf(withInputs, 'asset.bin').content, sha(content), 'the permitted local LFS content, verified against the pointer');
  assert.equal(entryOf(withInputs, 'wrong.bin').reasonCode, 'sentinel.capture.lfsObjectMismatch');
  assert.equal(entryOf(withInputs, 'vendor/sub').reasonCode, 'sentinel.capture.submoduleCapturedSeparately');
  assert.deepEqual([entryOf(withInputs, 'vendor/gone').disposition, entryOf(withInputs, 'vendor/gone').reasonCode],
    ['unreadable', 'sentinel.capture.submoduleCommitMissing']);
  assert.equal(entryOf(withInputs, 'vendor/unpermitted').reasonCode, 'sentinel.capture.submoduleNotCaptured');
  const subSource = withInputs.sources.find((s: any) => s.sourceId === 'app-sub');
  assert.deepEqual([subSource.repositoryId, subSource.commit], ['example/sub', subHead], 'an independent identity and commit');
  assert.equal(entryOf(withInputs, 'lib.ts', 'app-sub').disposition, 'included');
  assert.equal(withInputs.sources.some((s: any) => s.sourceId === 'app-gone'), false);
  // The provenance the envelope cannot carry is in the materialization.
  const appMat = (await openSnapshot(fx.store, withInputs.id)).materialization.sources.find(m => m.sourceId === 'app')!;
  assert.deepEqual(appMat.files.find(f => f.path === 'asset.bin')!.lfs, { oid: oidHex, size: content.length });
  assert.deepEqual(appMat.gitlinks.map(g => [g.path, g.commit]),
    [['vendor/gone', '1'.repeat(40)], ['vendor/sub', subHead], ['vendor/unpermitted', subHead]]);
});

