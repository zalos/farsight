// Generates the draft Sentinel JSON schemas from the canonical types in src/contracts/ (the one source).
// Writes schemas/<kind>.schema.json and src/schemas.generated.ts; --check fails when either differs.
import { createGenerator } from 'ts-json-schema-generator';
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const pkg = fileURLToPath(new URL('../', import.meta.url));
const ENVELOPES = {
  snapshot: ['sentinel-snapshot/draft-1', 'SnapshotEnvelope'],
  run: ['sentinel-run/draft-1', 'RunEnvelope'],
  work: ['sentinel-work/draft-1', 'WorkEnvelope'],
  attempt: ['sentinel-attempt/draft-1', 'AttemptEnvelope'],
  observation: ['sentinel-observation/draft-1', 'ObservationEnvelope'],
  coverage: ['sentinel-coverage/draft-1', 'CoverageEnvelope'],
  disposition: ['sentinel-disposition/draft-1', 'DispositionEnvelope'],
  report: ['sentinel-report/draft-1', 'ReportEnvelope'],
  protocol: ['sentinel-worker/draft-1', 'ProtocolMessage'],
  rulepack: ['sentinel-rulepack/draft-1', 'RulePackManifest'],
  rulelock: ['sentinel-rulelock/draft-1', 'RuleLockEnvelope'],
  settings: ['sentinel-settings/draft-1', 'SettingsEnvelope'],
  repoconfig: ['sentinel-repoconfig/draft-1', 'RepoConfigEnvelope'],
  policy: ['sentinel-policy/draft-1', 'EffectivePolicyEnvelope'],
  adoption: ['sentinel-adoption/draft-1', 'AdoptionEnvelope'],
  receipt: ['sentinel-receipt/draft-1', 'ReceiptEnvelope'],
  admission: ['sentinel-admission/draft-1', 'AdmissionEnvelope'],
  controls: ['sentinel-controls/draft-1', 'ControlFactsEnvelope'],
  plan: ['sentinel-plan/draft-1', 'PlanEnvelope'],
  paths: ['sentinel-paths/draft-1', 'PathEvidenceEnvelope'],
  deepimport: ['sentinel-deep-import/draft-1', 'DeepImportEnvelope'],
  servicecapabilities: ['sentinel-service-capabilities/draft-1', 'ServiceCapabilities'],
  runinspection: ['sentinel-run-inspection/draft-1', 'RunInspection'],
  inspectionpage: ['sentinel-inspection-page/draft-1', 'InspectionPage'],
  reportdelivery: ['sentinel-report-delivery/draft-1', 'ReportDelivery'],
  deliverychunk: ['sentinel-delivery-chunk/draft-1', 'DeliveryChunk'],
  controlcapabilities: ['sentinel-control-capabilities/draft-1', 'ControlCapabilities'],
  controloutcome: ['sentinel-control-outcome/draft-1', 'ControlOutcome'],

};

const generator = createGenerator({
  path: `${pkg}src/contracts/*.ts`,
  tsconfig: `${pkg}tsconfig.json`,
  type: '*',
  additionalProperties: false,
  expose: 'export',
  topRef: true,
  jsDoc: 'extended',
  skipTypeCheck: true,
});

const files = new Map();
const all = {};
for (const [kind, [version, type]] of Object.entries(ENVELOPES)) {
  const schema = generator.createSchema(type);
  const fileName = `${version.replace('/', '.')}.schema.json`;
  schema.$id = `https://github.com/zalos/farsight/packages/sentinel/schemas/${fileName}`;
  schema.title = version;
  all[kind] = schema;
  files.set(`${pkg}schemas/${fileName}`, JSON.stringify(schema, null, 2) + '\n');
}
files.set(`${pkg}src/schemas.generated.ts`,
  '// Generated by scripts/generate-schemas.mjs from src/contracts/. Do not edit.\n' +
  'export default ' + JSON.stringify(all) + ' as const;\n');

if (process.argv.includes('--check')) {
  const stale = [...files].filter(([file, text]) => { try { return readFileSync(file, 'utf8') !== text; } catch { return true; } });
  const expected = new Set([...files.keys()].filter(f => f.includes('/schemas/')).map(f => f.slice(f.lastIndexOf('/') + 1)));
  const extra = readdirSync(`${pkg}schemas`).filter(f => !expected.has(f));
  if (stale.length || extra.length) {
    console.error('Sentinel schemas differ from src/contracts; run pnpm --filter @farsight/sentinel schemas');
    for (const [file] of stale) console.error(`  stale: ${file.slice(pkg.length)}`);
    for (const file of extra) console.error(`  unexpected: schemas/${file}`);
    process.exit(1);
  }
} else {
  mkdirSync(`${pkg}schemas`, { recursive: true });
  for (const [file, text] of files) writeFileSync(file, text);
}
