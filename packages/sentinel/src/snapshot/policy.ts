// The capture policy and the path rules every source shares. Capture never reads repository ignore files:
// what is in scope is the owner's policy, so an input cannot disappear because the repository asks it to.
import { createHash } from 'node:crypto';
import { posix } from 'node:path';
import { canonicalJson } from '../store/objects.js';
import type { CaptureReasonCode } from './errors.js';

export interface CapturePolicy {
  /** Largest file captured, in bytes (at most the store's 16 MiB object limit). Default 8 MiB. */
  readonly maxFileBytes: number;
  /** Total bytes captured across all sources. Default 1 GiB. */
  readonly maxTotalBytes: number;
  /** Entries one snapshot records, boundaries included (at most 200000). Default 20000, which keeps the manifest inside the 4 MiB envelope limit for ordinary paths. */
  readonly maxEntries: number;
  /** Source-relative paths (a file or a whole folder) the owner puts out of scope, per source id or `*`. */
  readonly exclude: Readonly<Record<string, readonly string[]>>;
  /** Folder names that hold installed dependencies or tool caches, excluded wherever they appear. */
  readonly dependencyCaches: readonly string[];
  /** Folder names whose files are flagged generated wherever they appear. */
  readonly generatedDirectories: readonly string[];
  /** File-name suffixes flagged generated. */
  readonly generatedSuffixes: readonly string[];
  /** A working copy is read, stored and read again; this many attempts before it is reported unstable. */
  readonly stabilityAttempts: number;
}

export const DEFAULT_CAPTURE_POLICY: CapturePolicy = Object.freeze({
  maxFileBytes: 8 * 1024 * 1024,
  maxTotalBytes: 1024 * 1024 * 1024,
  maxEntries: 20_000,
  exclude: Object.freeze({}),
  dependencyCaches: Object.freeze(['node_modules', 'bower_components', 'jspm_packages', '.pnpm-store', '.yarn/cache', '.yarn/unplugged', '.gradle', '.m2']),
  generatedDirectories: Object.freeze(['__generated__', 'generated']),
  generatedSuffixes: Object.freeze(['.generated.ts', '.generated.tsx', '.generated.js', '.generated.java', '.g.ts', '_pb.js', '_pb.d.ts', '.pb.ts']),
  stabilityAttempts: 3,
});

/** Header phrases that mark a file as generated by a tool (checked in its first 512 bytes). */
const GENERATED_MARKERS = [/@generated\b/, /\bCode generated\b.*\bDO NOT EDIT\b/i, /\bauto-?generated\b.*\bdo not (edit|modify)\b/i];

const MAX_FILE_LIMIT = 16 * 1024 * 1024;
const MAX_ENTRIES_LIMIT = 200_000;

export function digestOf(value: unknown): string {
  return `sha256:${createHash('sha256').update(canonicalJson(value)).digest('hex')}`;
}

/** Fills defaults and checks bounds; throws a message naming the bad field. */
export function resolvePolicy(given: Partial<CapturePolicy> | undefined): CapturePolicy {
  const p = { ...DEFAULT_CAPTURE_POLICY, ...(given ?? {}) };
  const int = (v: unknown, lo: number, hi: number, name: string) => {
    if (!Number.isSafeInteger(v) || (v as number) < lo || (v as number) > hi) throw new Error(`${name} must be an integer in ${lo}..${hi}`);
  };
  int(p.maxFileBytes, 0, MAX_FILE_LIMIT, 'maxFileBytes');
  int(p.maxTotalBytes, 0, Number.MAX_SAFE_INTEGER, 'maxTotalBytes');
  int(p.maxEntries, 1, MAX_ENTRIES_LIMIT, 'maxEntries');
  int(p.stabilityAttempts, 1, 10, 'stabilityAttempts');
  const strings = (v: unknown, name: string) => {
    if (!Array.isArray(v) || v.some(s => typeof s !== 'string' || s.length === 0)) throw new Error(`${name} must be a list of names`);
  };
  strings(p.dependencyCaches, 'dependencyCaches');
  strings(p.generatedDirectories, 'generatedDirectories');
  strings(p.generatedSuffixes, 'generatedSuffixes');
  if (!p.exclude || typeof p.exclude !== 'object') throw new Error('exclude must map source ids to paths');
  for (const [k, v] of Object.entries(p.exclude)) {
    strings(v, `exclude.${k}`);
    for (const path of v) if (!isRecordablePath(path)) throw new Error(`exclude.${k} has an unsafe path`);
  }
  return Object.freeze({
    ...p,
    exclude: Object.freeze(Object.fromEntries(Object.entries(p.exclude).map(([k, v]) => [k, Object.freeze([...v].sort())]))),
    dependencyCaches: Object.freeze([...p.dependencyCaches].sort()),
    generatedDirectories: Object.freeze([...p.generatedDirectories].sort()),
    generatedSuffixes: Object.freeze([...p.generatedSuffixes].sort()),
  });
}

/** A path the snapshot contract can record (see `RelativePath`). */
export function isRecordablePath(path: string): boolean {
  if (path.length === 0 || path.length > 4096 || path.includes('\\') || path.includes('\u0000')) return false;
  return path.split('/').every(s => s !== '' && s !== '.' && s !== '..');
}

export interface NameCheck {
  /** The name as recorded: the UTF-8 text, or a marked hexadecimal form when it cannot be recorded as text. */
  readonly name: string;
  readonly refused?: CaptureReasonCode;
}

/** Decodes and checks one directory-entry name. `.git` is refused inside committed trees (`inTree`). */
export function checkName(raw: Buffer | string, inTree: boolean): NameCheck {
  let name: string;
  if (typeof raw === 'string') name = raw;
  else {
    try { name = new TextDecoder('utf-8', { fatal: true }).decode(raw); } catch {
      return { name: `�hex-${raw.toString('hex')}`, refused: 'sentinel.capture.pathEncoding' };
    }
  }
  const hex = () => `�hex-${Buffer.from(name, 'utf8').toString('hex')}`;
  if (name === '' || name === '.' || name === '..' || name.includes('/') || name.includes('\u0000')) {
    return { name: hex(), refused: 'sentinel.capture.unsafePath' };
  }
  if (name.includes('\\')) return { name: hex(), refused: 'sentinel.capture.unsafePath' };
  if (inTree && name.toLowerCase().replace(/[. ]+$/, '') === '.git') return { name: hex(), refused: 'sentinel.capture.unsafePath' };
  return { name };
}

export const joinPath = (dir: string, name: string) => (dir === '' ? name : `${dir}/${name}`);

/** Why a folder is not listed, or undefined when it is listed. */
export function folderExclusion(policy: CapturePolicy, sourceId: string, path: string, storeRel: string | undefined):
  CaptureReasonCode | undefined {
  if (storeRel !== undefined && path === storeRel) return 'sentinel.capture.excludedStore';
  if (excludedByPolicy(policy, sourceId, path)) return 'sentinel.capture.excludedByPolicy';
  for (const cache of policy.dependencyCaches) {
    if (path === cache || path.endsWith(`/${cache}`)) return 'sentinel.capture.excludedDependencyCache';
  }
  return undefined;
}

export function excludedByPolicy(policy: CapturePolicy, sourceId: string, path: string): boolean {
  for (const list of [policy.exclude['*'] ?? [], policy.exclude[sourceId] ?? []]) {
    if (list.includes(path)) return true;
  }
  return false;
}

/** Whether a file is generated: a generated folder on its path, a generated suffix, or a generator's header. */
export function isGenerated(policy: CapturePolicy, path: string, head: Buffer | undefined): boolean {
  const segments = path.split('/');
  if (segments.slice(0, -1).some(s => policy.generatedDirectories.includes(s))) return true;
  if (policy.generatedSuffixes.some(s => path.endsWith(s))) return true;
  if (head) {
    const text = head.subarray(0, 512).toString('latin1');
    if (GENERATED_MARKERS.some(m => m.test(text))) return true;
  }
  return false;
}

/** A symbolic link's target, judged without following it. */
export function symlinkVerdict(path: string, target: string): CaptureReasonCode {
  if (target.startsWith('/') || target.includes('\u0000')) return 'sentinel.capture.symlinkEscapes';
  const resolved = posix.normalize(posix.join(posix.dirname(path), target));
  if (resolved === '..' || resolved.startsWith('../') || resolved.startsWith('/')) return 'sentinel.capture.symlinkEscapes';
  return 'sentinel.capture.symlinkNotFollowed';
}

/** The fold used to find paths that restore onto the same name on case-insensitive or normalising file systems. */
export const foldPath = (p: string) => p.normalize('NFC').toLowerCase();

/** A Git LFS pointer's content id and size, or undefined when `bytes` is not one. */
export function lfsPointer(bytes: Buffer): { oid: string; size: number } | undefined {
  if (bytes.length > 1024) return undefined;
  const text = bytes.toString('utf8');
  if (!text.startsWith('version https://git-lfs.github.com/spec/v1\n')) return undefined;
  const oid = /^oid sha256:([0-9a-f]{64})$/m.exec(text);
  const size = /^size (\d+)$/m.exec(text);
  if (!oid || !size || !Number.isSafeInteger(Number(size[1]))) return undefined;
  return { oid: oid[1]!, size: Number(size[1]) };
}
